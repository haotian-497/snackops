function apply(file) {
  const cases = JSON.parse(fs.readFileSync(file, "utf8"));
  let updated = 0;
  for (const item of cases) {
    if (golds[item.id]) {
      item.expectedReply = golds[item.id];
      updated += 1;
    }
  }
  const missing = Object.keys(golds).filter((id) => !cases.some((c) => c.id === id));
  fs.writeFileSync(file, `${JSON.stringify(cases, null, 2)}\n`);
  const withGold = cases.filter((c) => String(c.expectedReply || "").trim()).length;
  console.log({
    file,
    updated,
    withGold,
    total: cases.length,
    missing,
  });
}

